"""DSP lookup tables for PULSAR-8 (build/gen/pz_tables.h).

  SINE[1025]      Q15 sine, one period + guard point (linear interpolation)
  EXP2_16[192]    2^(n / 192) in Q16: 1/16-semitone steps over one octave
  SVF_G[128]      tan(pi f / fs) in Q16, f = CUTOFF_HZ(i), 20 Hz .. 18 kHz exponential
  CUTOFF_HZ[128]  the frequencies (UI)
  DECAY_K[128]    per-sample multiplier Q30 reaching -60 dB after DECAY_MS(i)
  DECAY_MS[128]   1.5 ms .. ~9 s exponential (UI)
  VEL_Q15[128]    velocity -> gain (curve ~ x^1.6)
  LVL_Q15[128]    level fader -> gain (audio taper, 0 = silent, 100 = unity, 127 ~ +3 dB)
  PAN_L/PAN_R[128] constant-power pan, Q15
  ULAW[256]       mu-law decode to Q15 (linear)
"""
import math
import sys
from pathlib import Path

FS = 44100


def cutoff_hz(i):
    return 20.0 * (18000.0 / 20.0) ** (i / 127.0)


def decay_ms(i):
    return 1.5 * 2.0 ** (i / 10.0)          # 127 -> ~9.3 s


def ulaw_decode(b):
    b = ~b & 0xFF
    sign = b & 0x80
    exp = (b >> 4) & 7
    man = b & 0x0F
    v = ((man << 3) + 0x84) << exp
    v -= 0x84
    return -v if sign else v                  # +-32124


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main(dst):
    L = ["/* generated by tools/gen_tables.py: do not edit */", "#pragma once", "#include <stdint.h>", ""]
    L += arr("SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
    L += arr("EXP2_16", "uint32_t", [int(round(65536 * 2 ** (n / 192.0))) for n in range(192)])
    g = []
    for i in range(128):
        f = min(cutoff_hz(i), FS * 0.45)
        g.append(int(round(65536 * math.tan(math.pi * f / FS))))
    L += arr("SVF_G", "int32_t", g)
    L += arr("CUTOFF_HZ", "uint16_t", [int(round(cutoff_hz(i))) for i in range(128)])
    k = []
    for i in range(128):
        n = decay_ms(i) * FS / 1000.0
        k.append(int(round((1 << 30) * math.exp(math.log(0.001) / n))))
    L += arr("DECAY_K", "int32_t", k)
    L += arr("DECAY_MS", "uint16_t", [min(65535, int(round(decay_ms(i)))) for i in range(128)])
    L += arr("VEL_Q15", "int16_t", [int(round(32767 * (v / 127.0) ** 1.6)) for v in range(128)])
    lv = []
    for v in range(128):
        if v == 0:
            lv.append(0)
        else:
            db = 40.0 * math.log10(v / 100.0)     # 50 -> -12 dB, 25 -> -24 dB, 127 -> +4 dB
            lv.append(min(32767 * 2, int(round(32767 * 10 ** (db / 20.0)))))
    L += arr("LVL_Q15", "int32_t", lv)
    L += arr("PAN_L", "int16_t", [int(round(32767 * math.cos(math.pi / 2 * p / 127.0))) for p in range(128)])
    L += arr("PAN_R", "int16_t", [int(round(32767 * math.sin(math.pi / 2 * p / 127.0))) for p in range(128)])
    L += arr("ULAW", "int16_t", [ulaw_decode(b) for b in range(256)])
    L.append(f"#define PZ_TABLES_FS {FS}")
    Path(dst).write_text("\n".join(L) + "\n")
    print(f"tables: {dst}")


if __name__ == "__main__":
    main(sys.argv[1])
