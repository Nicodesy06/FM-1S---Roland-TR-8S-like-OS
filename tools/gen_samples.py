"""Drum recordings for the sample-based kits (build/gen/pz_samples.h).

The CC0 recordings in assets/samples-cc0/KIT (Versilian Studios VCSL) are
mixed to mono, trimmed at the attack, cut to a musical length with a fade,
normalised, resampled to RATE and stored as 8-bit mu-law: the companded 8-bit
format of the early-80s sample drum machines. The machine character (sample
clock, bit depth, filtering) is applied at run time per instrument (pz_dsp.c),
so one recording serves several vintage-style kits.

Pure Python (no numpy); the result is cached next to the output.
"""
import hashlib
import math
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "assets" / "samples-cc0" / "KIT"
RATE = 24000

# (C name, file, length in seconds, label)
SAMPLES = [
    ("BD", "10_kick_BDrumNew_hit_v5.wav", 0.45),
    ("SD", "11_snare_Snare2_HitSN_v7.wav", 0.40),
    ("LT", "16_tomlo_TomL_HitS_v4.wav", 0.55),
    ("HT", "17_tomhi_TomH_HitS_v4.wav", 0.45),
    ("CP", "13_clap_Clap_rr1.wav", 0.35),
    ("RS", "12_rim_sidestick.wav", 0.15),
    ("CH", "14_hihat_HitC_v3.wav", 0.16),
    ("OH", "15_ohat_HitO.wav", 0.70),
    ("CY", "18_crash_susCymb2_hit_f1.wav", 1.10),
    ("RD", "19_ride_susCymb2_stick_mf1.wav", 0.85),
    ("CB", "20_cowbell_Cowbell1_Normal_v3.wav", 0.30),
    ("TB", "00_Tamb1_Hit_v2_rr1_Mid.wav", 0.35),
    ("SH", "01_Mid_ShakerDouble_Down_rr1.wav", 0.20),
    ("CG", "02_Conga_HitN_v2_rr1_Sum.wav", 0.40),
    ("CL", "03_Claves1_Hit_v2_rr1_Mid.wav", 0.15),
    ("WB", "04_wood_click_mp.wav", 0.12),
]


def read_wav(p):
    w = wave.open(str(p))
    n, ch, sw, fr = w.getnframes(), w.getnchannels(), w.getsampwidth(), w.getframerate()
    raw = w.readframes(n)
    out = []
    for i in range(n):
        acc = 0.0
        for c in range(ch):
            o = (i * ch + c) * sw
            if sw == 2:
                v = struct.unpack_from("<h", raw, o)[0] / 32768.0
            elif sw == 3:
                b = raw[o:o + 3]
                v = int.from_bytes(b + (b"\xff" if b[2] & 0x80 else b"\x00"), "little", signed=True) / 8388608.0
            else:
                raise SystemExit(f"{p}: {sw * 8}-bit not supported")
            acc += v
        out.append(acc / ch)
    return out, fr


def resample(x, src, dst):
    """windowed-sinc low-pass + resampling (cutoff 0.45 dst)"""
    ratio = src / dst
    fc = 0.45 * dst / src if dst < src else 0.45
    half = 16
    n_out = int(len(x) / ratio)
    y = []
    for j in range(n_out):
        t = j * ratio
        i0 = int(t)
        acc = 0.0
        for k in range(i0 - half + 1, i0 + half + 1):
            if 0 <= k < len(x):
                d = t - k
                s = 2 * fc * (math.sin(2 * math.pi * fc * d) / (2 * math.pi * fc * d) if d else 1.0)
                w = 0.5 + 0.5 * math.cos(math.pi * d / half) if abs(d) < half else 0.0
                acc += x[k] * s * w
        y.append(acc)
    return y


def ulaw(v):
    """linear -1..1 -> 8-bit mu-law (G.711, 16-bit scale)"""
    s = int(round(max(-1.0, min(1.0, v)) * 32767))
    sign = 0x80 if s < 0 else 0
    s = min(abs(s), 32635) + 0x84
    exp = 7
    while exp > 0 and not (s & (0x4000 >> (7 - exp))):
        exp -= 1
    man = (s >> (exp + 3)) & 0x0F
    return ~(sign | (exp << 4) | man) & 0xFF


def process(name, fn, secs):
    x, fr = read_wav(KIT / fn)
    peak = max(abs(v) for v in x) or 1.0
    th = peak * 0.02
    start = next((i for i, v in enumerate(x) if abs(v) > th), 0)
    start = max(0, start - int(0.0005 * fr))
    x = x[start:start + int(secs * fr)]
    n = len(x)
    fade = int(n * 0.18)
    for i in range(fade):
        x[n - fade + i] *= math.cos(0.5 * math.pi * i / fade)
    y = resample(x, fr, RATE)
    pk = max(abs(v) for v in y) or 1.0
    y = [v / pk * 0.94 for v in y]
    return bytes(ulaw(v) for v in y)


def main(dst):
    dst = Path(dst)
    key = hashlib.sha256((Path(__file__).read_bytes() +
                          b"".join((KIT / f).read_bytes() for _, f, _ in SAMPLES))).hexdigest()
    cache = dst.with_suffix(".cache")
    if cache.exists() and dst.exists() and cache.read_text() == key:
        print(f"samples: cached ({dst.name})")
        return
    L = ["/* generated by tools/gen_samples.py from CC0 recordings (assets/samples-cc0): do not edit */",
         "#pragma once", "#include <stdint.h>", f"#define PCM_RATE {RATE}u", ""]
    names, total = [], 0
    for name, fn, secs in SAMPLES:
        b = process(name, fn, secs)
        total += len(b)
        L.append(f"static const uint8_t PCM_{name}[{len(b)}] = {{")
        for i in range(0, len(b), 24):
            L.append("    " + ",".join(str(v) for v in b[i:i + 24]) + ",")
        L.append("};")
        names.append((name, len(b)))
    L.append("typedef struct { const uint8_t *d; uint32_t n; } pcm_smp_t;")
    L.append("enum { " + ", ".join(f"SMP_{n}" for n, _ in names) + ", SMP_N };")
    L.append("static const pcm_smp_t PCM_SMP[SMP_N] = {" + ", ".join(f"{{PCM_{n}, {k}}}" for n, k in names) + "};")
    dst.write_text("\n".join(L) + "\n")
    cache.write_text(key)
    print(f"samples: {len(names)} recordings, {total} B mu-law at {RATE} Hz")


if __name__ == "__main__":
    main(sys.argv[1])
