"""Anti-aliased UI fonts for PULSAR-8 (build/gen/pz_fonts.h).

Inter Display (SIL OFL 1.1, assets/fonts/Inter-LICENSE.txt), rendered at a few pixel sizes with
4-bit coverage. Each glyph is cropped to its ink; the C renderer (pz_gfx.c) blends it onto
whatever is drawn below. Wide tracking is added to the small sizes: they read like the screened
legends of a hardware panel.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parents[1] / "assets" / "fonts"
# name, file, pixel size, extra tracking, first, last
SPECS = [
    ("F7", "InterDisplay-Bold.otf", 10, 1, 32, 95),       # legends (capitals, digits)
    ("F9", "InterDisplay-Bold.otf", 13, 1, 32, 95),       # labels, values
    ("F12", "InterDisplay-Bold.otf", 17, 0, 32, 95),      # names
    ("F20", "InterDisplay-Bold.otf", 28, 0, 32, 95),      # big values
]


def render(name, fname, px, track, first, last):
    font = ImageFont.truetype(str(FONTS / fname), px)
    asc, desc = font.getmetrics()
    h = asc + desc
    glyphs = []
    for c in range(first, last + 1):
        ch = chr(c)
        adv = int(round(font.getlength(ch))) + track
        img = Image.new("L", (px * 2 + 4, h), 0)
        ImageDraw.Draw(img).text((2, 0), ch, font=font, fill=255)
        bb = img.getbbox()
        if not bb:
            glyphs.append((adv, 0, 0, b""))
            continue
        x0, x1 = bb[0], bb[2]
        w = x1 - x0
        data = bytearray()
        for y in range(h):
            row = [img.getpixel((x, y)) for x in range(x0, x1)]
            q = [min(15, (v + 8) // 17) for v in row] + [0]
            for i in range(0, w, 2):
                data.append(q[i] << 4 | q[i + 1])
        glyphs.append((adv, w, x0 - 2, bytes(data)))
    return h, asc, glyphs


def main(dst):
    L = ["/* generated by tools/gen_fonts.py from Inter Display (SIL OFL 1.1): do not edit */", "#pragma once",
         "#include <stdint.h>",
         "typedef struct { uint8_t h, asc, first, last; const uint8_t *adv, *w; const int8_t *xo;",
         "                 const uint16_t *off; const uint8_t *data; } pzfont_t;", ""]
    total = 0
    for name, fname, px, track, first, last in SPECS:
        h, asc, gl = render(name, fname, px, track, first, last)
        data, offs = bytearray(), []
        for g in gl:
            offs.append(len(data))
            data += g[3]
        total += len(data)
        L.append(f"static const uint8_t {name}_DATA[{max(1, len(data))}] = {{" + ",".join(map(str, data or b'\\0')) + "};")
        L.append(f"static const uint16_t {name}_OFF[{len(gl)}] = {{" + ",".join(map(str, offs)) + "};")
        L.append(f"static const uint8_t {name}_ADV[{len(gl)}] = {{" + ",".join(str(g[0]) for g in gl) + "};")
        L.append(f"static const uint8_t {name}_W[{len(gl)}] = {{" + ",".join(str(g[1]) for g in gl) + "};")
        L.append(f"static const int8_t {name}_XO[{len(gl)}] = {{" + ",".join(str(g[2]) for g in gl) + "};")
        L.append(f"static const pzfont_t {name} = {{{h}, {asc}, {first}, {last}, {name}_ADV, {name}_W, {name}_XO, "
                 f"{name}_OFF, {name}_DATA}};")
        L.append("")
    Path(dst).write_text("\n".join(L) + "\n")
    print(f"fonts: {len(SPECS)} sizes, {total} B")


if __name__ == "__main__":
    main(sys.argv[1])
